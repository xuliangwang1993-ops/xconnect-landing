#!/usr/bin/env python3
"""站 03d · AOI 能力表：site/data/aoi.json 的 12 个模块 → site/data/aoi-modules.js（左栏 M00–M11 表用）
              + site/i18n/en-aoi.js（名称/摘要的英文，取自 i18n/en-tree.js 已有译文；role 手译）。
只含公开的架构元数据（与 aoi-tree.html 同源），不含用户/订单/Pod/运行数据。"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
src = json.loads((SITE / "data/aoi.json").read_text())
tree_en = (SITE / "i18n/en-tree.js").read_text()

ROLE_EN = {
    "契约 / 事件总线 / 存储": "Contracts / event bus / storage",
    "指令解析、模型路由": "Instruction parsing, model routing",
    "注册表、来源链": "Registry, provenance chains",
    "排队、配额、审批": "Queueing, quotas, approvals",
    "执行器、证据留存": "Executor, evidence retention",
    "验收、仲裁": "Acceptance, adjudication",
    "体检、修复": "Health check, repair",
    "Recipe / Capability": "Recipe / Capability",
    "能力可视化、助手面": "Capability visualisation, assistant surface",
    "沙箱构建": "Sandboxed build",
    "可选": "Optional",
    "Assembly / E2E": "Assembly / E2E",
}
WAVE_EN = {"A": "Wave A · foundation", "B": "Wave B · execution", "C": "Wave C · extension", "D": "Wave D · assembly"}

def en_of(zh):
    m = re.search(r'^\s*"%s"\s*:\s*"((?:[^"\\]|\\.)*)"' % re.escape(zh), tree_en, re.M)
    return json.loads('"' + m.group(1) + '"') if m else None

mods, en = [], {}
for m in src["modules"]:
    mods.append({k: m[k] for k in ("code", "name", "role", "summary", "wave", "optional")} | {"stations": m.get("stations", [])})
    e = en_of(m["code"] + " " + m["name"])           # en-tree 里名称的键是 "M00 公共底座"
    if not e and m["code"] == "M10": e = "M10 Legacy Compatibility Bridge"   # en-tree 里带「（可选）」后缀，手补
    if e: en[m["name"]] = re.sub(r"^M\d+\s+", "", e)
    e = en_of(m["summary"])
    if e: en[m["summary"]] = e
    if m["role"] in ROLE_EN: en[m["role"]] = ROLE_EN[m["role"]]
for w, e in WAVE_EN.items(): en["施工批次 " + w] = e
en.update({
    "AOI 能力 · M00–M11": "AOI capabilities · M00–M11",
    "AOI 视图": "AOI view",
    "AOI 能力树视图（公开静态页，不含个人数据）": "AOI capability tree view (public static page, no personal data)",
    "打开 AOI 能力树 →": "Open the AOI capability tree →",
    "12 个施工模块；亮起的是当前所选工位用到的模块。公开架构信息，不含个人数据。":
        "12 build modules; the highlighted ones are used by the selected station. Public architecture info, no personal data.",
    "接入工位：": "Used by stations:",
    "暂无工位接入": "No station uses it yet",
    "可选模块": "Optional module",
    "工作台（预览）": "Workbench (preview)",
    "工作台（独立服务，含设置）。需用自己的网关 key 登录；与本页账号无关": "Workbench (separate service, includes Settings). Sign in with your own gateway key; independent of this page's account",
})
(SITE / "data/aoi-modules.js").write_text("window.XCF_AOI_MODULES = " + json.dumps({"modules": mods}, ensure_ascii=False) + ";\n")
(SITE / "i18n/en-aoi.js").write_text(
    "/* en dictionary — AOI capability table (generated by build/03d_aoi_table.py). Keys are the exact Chinese source text. */\n"
    "(function () {\n  if (!window.XCI) return;\n  window.XCI.add(" + json.dumps(en, ensure_ascii=False, indent=2) + ");\n})();\n")
print("modules", len(mods), "en keys", len(en))
